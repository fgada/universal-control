    static func mapping(for usage: UInt16) -> MacKeyMapping? {
        keyMappings[usage]
    }

    static func modifierBit(for usage: UInt16) -> Int? {
        guard usage >= 0xE0, usage <= 0xE7 else { return nil }
        return Int(usage - 0xE0)
    }

    static func modifierUsage(forBit bit: Int) -> UInt16 {
        0xE0 + UInt16(bit)
    }

    static func eventFlags(for modifierMask: UInt8) -> CGEventFlags {
        var flags: CGEventFlags = []
        if modifierMask & 0b0001_0001 != 0 { flags.insert(.maskControl) }
        if modifierMask & 0b0010_0010 != 0 { flags.insert(.maskShift) }
        if modifierMask & 0b0100_0100 != 0 { flags.insert(.maskAlternate) }
        if modifierMask & 0b1000_1000 != 0 { flags.insert(.maskCommand) }
        return flags
    }
